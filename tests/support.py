def tone(freq_hz, seconds, amp=0.5, sr=SR):
    """A pure sine of known frequency and amplitude."""
    t = np.arange(int(round(seconds * sr))) / float(sr)
    return (amp * np.sin(2.0 * np.pi * freq_hz * t)).astype(np.float32)


def quiet_noise(seconds, amp=1e-3, seed=0, sr=SR):
    """Room tone: low-level gaussian noise, well above digital silence."""
    rng = np.random.default_rng(seed)
    return (rng.standard_normal(int(round(seconds * sr))) * amp).astype(np.float32)


def bursty_speech(freqs, cycles=8, quiet_s=1.0, loud_s=4.0, amp=0.5):
    """Tone bursts separated by room tone.

    audio_metrics' VAD takes the 10th percentile of frame energy as the floor
    and calls anything 8 dB above it speech, so a signal has to have both a
    quiet part and a loud part before any speech-conditioned metric exists at
    all. Cycling `freqs` across the bursts is how a monotone signal and a
    pitch-varying one are built from the same helper.
    """
    parts = []
    for i in range(cycles):
        parts.append(quiet_noise(quiet_s, seed=i))
        parts.append(tone(freqs[i % len(freqs)], loud_s, amp=amp))
    return np.concatenate(parts)



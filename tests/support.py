def words(count, start, end, speaker, stem="alpha"):
    """`count` evenly-spaced word entries with per-word speaker labels."""
    step = (end - start) / float(count)
    return [{"word": f"{stem}{i}",
             "start": start + i * step,
             "end": start + (i + 1) * step,
             "speaker": speaker} for i in range(count)]

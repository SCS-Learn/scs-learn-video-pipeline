def good_value(mid):
    """A raw value that scores 1.0 for this metric."""
    scale = rubric.METRICS[mid]["scale"]
    if scale[0] == "bool":
        return True
    if scale[0] == "ramp":
        return scale[2]
    _, _hl, lo, hi, _hh = scale
    return (lo + hi) / 2.0


def mediocre_value(mid, fraction=0.4):
    """A raw value that scores partially, so remediation has something to do."""
    scale = rubric.METRICS[mid]["scale"]
    if scale[0] == "bool":
        return False
    if scale[0] == "ramp":
        _, bad, good = scale
        return bad + fraction * (good - bad)
    _, hard_lo, lo, _hi, _hh = scale
    return hard_lo + fraction * (lo - hard_lo)


def full_metrics(quality="good"):
    """Every rubric metric measured, plus the raw fields the gates read."""
    pick = good_value if quality == "good" else mediocre_value
    m = {mid: pick(mid) for mid in rubric.METRICS}
    m["duration_s"] = 4773.7
    m["duration_min"] = 4773.7 / 60.0
    m["speech_pct"] = 55.0
    m["asr_confidence"] = -0.5
    m["instructor_in_frame_pct"] = 85.0
    return m



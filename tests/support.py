def probe_info(camera=True, audio=True, screen=True,
               cam_duration=4773.7, scr_duration=5000.0):
    """The `probe_info` shape score.evaluate expects."""
    cam = None
    if camera:
        cam = {"path": "camera.mp4", "has_video": True, "has_audio": audio,
               "duration": cam_duration, "width": 1920, "height": 1080}
    scr = None
    if screen:
        scr = {"path": "screen.mp4", "has_video": True, "has_audio": False,
               "duration": scr_duration, "width": 1920, "height": 1080}
    return {"camera": cam, "screen": scr}



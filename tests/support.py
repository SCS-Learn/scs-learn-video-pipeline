VIDEO_W, VIDEO_H = 320, 192


def black_frame(w=VIDEO_W, h=VIDEO_H):
    return np.zeros((h, w), np.uint8)


def slide_frame(variant, w=VIDEO_W, h=VIDEO_H):
    """A lit, textured, clearly-not-black frame; `variant` changes the content.

    Successive variants differ over about a third of the frame, comfortably
    above video_metrics.SLIDE_CHANGE_DIFF (2.5 mean absolute levels) -- a real
    slide transition averages far more than that, and the threshold exists to
    sit clear of pointer movement and encoder noise.
    """
    f = np.full((h, w), 40, np.uint8)
    f[20 * h // 192:80 * h // 192, 20:200] = 220
    f[90 * h // 192:170 * h // 192, 20:w - 20] = np.uint8(30 + (variant % 6) * 40)
    return f


def pillarboxed_frame(variant, w=VIDEO_W, h=VIDEO_H):
    """A 4:3 deck inside a 16:9 frame: permanent black bars left and right."""
    f = black_frame(w, h)
    x0, x1 = w // 8, w - w // 8          # centre three quarters
    f[:, x0:x1] = 40
    f[20 * h // 192:80 * h // 192, x0 + 10:x1 - 10] = 220
    f[90 * h // 192:170 * h // 192, x0 + 5:x1 - 5] = \
        np.uint8(30 + (variant % 6) * 40)
    return f


def write_gray_video(path, frames, fps=10, w=VIDEO_W, h=VIDEO_H):
    """Encode grayscale numpy frames to H.264, every frame a keyframe.

    `-g 1` matters: src.scan.media.iter_frames samples the keyframe grid, so
    an all-keyframe file makes the frame sequence the test wrote exactly the
    frame sequence the measurement sees. `-qp 0` keeps luma lossless so the
    black/lit thresholds in video_metrics are not decided by the encoder.
    """
    cmd = ["ffmpeg", "-y", "-v", "error", "-f", "rawvideo", "-pix_fmt", "gray",
           "-s", f"{w}x{h}", "-r", str(fps), "-i", "-",
           "-c:v", "libx264", "-preset", "ultrafast", "-qp", "0",
           "-g", "1", "-pix_fmt", "yuv420p", path]
    proc = subprocess.Popen(cmd, stdin=subprocess.PIPE,
                            stdout=subprocess.DEVNULL,
                            stderr=subprocess.PIPE)
    try:
        for f in frames:
            proc.stdin.write(np.asarray(f, dtype=np.uint8).tobytes())
        proc.stdin.close()
    except BrokenPipeError:                                     # pragma: no cover
        pass
    err = proc.stderr.read().decode("utf-8", "replace")
    proc.stderr.close()
    if proc.wait() != 0:                                        # pragma: no cover
        raise RuntimeError(f"ffmpeg failed writing {path}: {err}")
    return path


